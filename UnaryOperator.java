public class UnaryOperator {
     public static void main(String[] args) {
        int X=5;
        int y=-X;
        System.out.println(y);
         int z=-y;
         System.out.println(z);

    //Pre Increments
         int a=10;
         System.out.println(++a);
         System.out.println(a);

    //Post Increment 
         System.out.println(a++);
         System.out.println(a);

    //Pre Decrements
          int b=11;
          System.out.println(--b);
          System.out.println(b);

    // Post Decrements 
         System.out.println(b--);
         System.out.println(b);
     }
}
